function generateLanguagePackage(langCode) {
  const data = LANG_DATA[langCode];
  if (!data) return;

  const pkg = {
    ui: {
      ...data.ui,
      tagline: data.tagline,
      heroSub: data.heroSub,
      searchTitle: data.searchTitle,
      searchDesc: data.searchDesc,
      catTitle: data.catTitle,
      catDesc: data.catDesc,
      catLead: '{n} ' + data.catTitle.replace(/\s*\|\s*\{brand\}/, '').trim(),
      crumbHome: data.ui.crumbHome || 'Home',
      popularSearches: data.ui.popularSearches || 'Popular Searches'
    },
    home: {
      title: data.homeTitle,
      desc: data.homeDesc,
      h1: data.homeH1
    },
    commonFaq: [
      {
        q: data.ui.f1t + '?',
        a: data.ui.f1d + ' ' + data.ui.f2d
      },
      {
        q: data.ui.f2t + '?',
        a: data.ui.privacy + ' ' + data.ui.privL1
      }
    ],
    tools: {}
  };

  // Add category titles to UI
  for (const [catKey, catVal] of Object.entries(data.cats)) {
    pkg.ui['cat_' + catKey] = catVal;
  }

  // Populate 50 core tools
  for (const toolId of CORE_TOOLS) {
    const rawName = (data.toolsNames && data.toolsNames[toolId]) || toolId;
    
    // Ensure title <= 60 chars including ' | {brand}' (which is 11 chars)
    let baseTitle = rawName + ' – ' + (data.ui.tFree || 'Free Online');
    if (baseTitle.length + 11 > 60) {
      baseTitle = rawName;
      if (baseTitle.length + 11 > 60) {
        baseTitle = baseTitle.slice(0, 48).trim().replace(/[,\-–—\s]+$/, '');
      }
    }
    const title = baseTitle + ' | {brand}';

    // Ensure description 70 - 155 chars
    let desc = rawName + '. ' + data.ui.privacy;
    if (langCode === 'zh-cn') {
      desc = rawName + '。' + data.ui.privacy + ' 无需上传任何文件，直接在您的浏览器中极速且安全地处理完成。';
    } else if (langCode === 'zh-tw') {
      desc = rawName + '。' + data.ui.privacy + ' 無需上傳任何檔案，直接在您的瀏覽器中極速且安全地處理完成。';
    } else if (langCode === 'ja') {
      desc = rawName + '。' + data.ui.privacy + ' ファイル送信なしで、ブラウザ内で素早く安全に処理できます。';
    } else if (langCode === 'ko') {
      desc = rawName + '。' + data.ui.privacy + ' 파일 전송 없이 브라우저에서 안전하고 빠르게 처리할 수 있습니다.';
    } else {
      if (desc.length < 75) desc = desc + ' ' + (data.ui.f1d || '') + ' ' + (data.ui.tLocal || '');
    }
    if (desc.length < 72) desc = desc + ' ' + (data.ui.tLocal || '') + ' ' + (data.ui.tFree || '');
    if (desc.length > 155) desc = desc.slice(0, 150).trim().replace(/[,;\s]+$/, '') + '.';

    pkg.tools[toolId] = {
      name: rawName,
      short: rawName + ' – ' + (data.ui.tFree || 'Free'),
      title: title,
      desc: desc,
      h1: rawName,
      steps: [
        data.ui.stepUpload,
        data.ui.stepOptions,
        data.ui.stepDownload
      ],
      faq: [
        {
          q: data.ui.howTo + ' ' + rawName + '?',
          a: data.ui.privacy + ' ' + (data.ui.tNoSign || '') + '.'
        }
      ]
    };
  }

  const outPath = path.join(__dirname, '..', 'src', 'i18n', langCode + '.json');
  fs.writeFileSync(outPath, JSON.stringify(pkg, null, 1));
  console.log('Generated i18n package for ' + langCode + ' -> ' + outPath);
}

// Generate for all 14 languages
for (const langCode of Object.keys(LANG_DATA)) {
  generateLanguagePackage(langCode);
}
console.log('All 14 world languages generated successfully!');
